// Turns setup answers into an instance's Wrangler files, and reads them back. Pure: no
// files, no network. The public Worker's file is edited in place (its comments and any
// settings this does not manage stay); the dashboard's file is written whole.
//
// Options: {
//   name, accountId?, domains: string[] (none: workers.dev), apiHosts: string[],
//   namespaces: [network, site] rate-limit namespace IDs,
//   admin: null | { domains: string[], auth: 'password' | 'access',
//     access?: { team, aud, emails } (only when kept as values rather than secrets),
//     fileNames: boolean, database: { name, id } },
// }
import { applyEdits, modify, parse } from 'jsonc-parser';

const FORMAT = { formattingOptions: { insertSpaces: true, tabSize: 2 } };
const has = (text, path) =>
  path.reduce((node, key) => (node == null ? undefined : node[key]), parse(text)) !== undefined;
/** Sets a value at a path, keeping the rest of the text; undefined removes it. */
function set(text, path, value) {
  if (value === undefined && !has(text, path)) return text;
  return applyEdits(text, modify(text, path, value, FORMAT));
}
const MANAGED_VARS = ['SITE', 'API_HOSTS', 'RECORD_FILE_NAMES'];
const HOST = /^(?=.{1,253}$)([a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/;
const WORKER = /^[a-z0-9](?:[a-z0-9-]{0,55}[a-z0-9])?$/;

/** '../' for each folder between the repository and an instance folder. */
export function instancePrefix(dir) {
  return dir
    .split(/[\\/]/)
    .filter((part) => part && part !== '.')
    .map(() => '../')
    .join('');
}

/** The first pair of rate-limit namespaces (1001/1002, 2001/2002, …) nobody uses yet. */
export function nextNamespaces(used) {
  for (let n = 1; ; n++) {
    const pair = [`${n}001`, `${n}002`];
    if (!pair.some((id) => used.includes(id))) return pair;
  }
}

export function validateOptions(options) {
  if (!WORKER.test(options.name))
    throw new Error(
      'The name may use lowercase letters, digits and dashes, up to 57 characters (the dashboard adds "-admin").',
    );
  for (const host of [...options.domains, ...options.apiHosts, ...(options.admin?.domains ?? [])])
    if (!HOST.test(host))
      throw new Error(`"${host}" is not a domain name, like send.example.com (no https://).`);
  if (options.apiHosts.length && !options.domains.length)
    throw new Error('A host for the command line needs the site on a custom domain too.');
  if (options.admin && (!options.admin.database?.name || !options.admin.database?.id))
    throw new Error('The dashboard needs its activity database.');
}

const routes = (hosts) => hosts.map((pattern) => ({ pattern, custom_domain: true }));
const databases = (admin, prefix) => [
  {
    binding: 'ACTIVITY',
    database_name: admin.database.name,
    database_id: admin.database.id,
    migrations_dir: `${prefix}migrations`,
  },
];

function renderPublic(text, options, prefix) {
  const { domains, apiHosts, admin } = options;
  text = set(text, ['$schema'], `${prefix}node_modules/wrangler/config-schema.json`);
  text = set(text, ['name'], options.name);
  text = set(text, ['account_id'], options.accountId);
  text = set(text, ['main'], `${prefix}worker/index.ts`);
  text = set(text, ['assets', 'directory'], prefix ? `${prefix}dist` : './dist');
  text = set(text, ['workers_dev'], !domains.length);
  text = set(text, ['routes'], domains.length ? routes([...domains, ...apiHosts]) : undefined);
  // A site with several addresses names one, so they all pair (see docs/configuration.md).
  const values = {
    SITE: domains.length + apiHosts.length > 1 ? `https://${domains[0]}` : undefined,
    API_HOSTS: apiHosts.length ? apiHosts : undefined,
    RECORD_FILE_NAMES: admin && !admin.fileNames ? false : undefined,
  };
  for (const key of MANAGED_VARS) text = set(text, ['vars', key], values[key]);
  const vars = parse(text).vars;
  if (vars && !Object.keys(vars).length) text = set(text, ['vars'], undefined);
  text = set(text, ['d1_databases'], admin ? databases(admin, prefix) : undefined);
  const limits = parse(text).ratelimits ?? [];
  limits.forEach((limit, index) => {
    const id = { NETWORK_RATE: options.namespaces[0], SITE_RATE: options.namespaces[1] }[
      limit.name
    ];
    if (id) text = set(text, ['ratelimits', index, 'namespace_id'], id);
  });
  return text;
}

function renderAdmin(options, prefix, compatibilityDate) {
  const { admin } = options;
  const config = {
    $schema: `${prefix}node_modules/wrangler/config-schema.json`,
    // The dashboard: see docs/admin.md. Generated by npm run setup.
    name: `${options.name}-admin`,
    ...(options.accountId ? { account_id: options.accountId } : {}),
    main: `${prefix}admin/index.ts`,
    compatibility_date: compatibilityDate,
    workers_dev: !admin.domains.length,
    preview_urls: false,
    assets: { directory: `${prefix}admin/public`, binding: 'ASSETS', run_worker_first: true },
    d1_databases: databases(admin, prefix),
    durable_objects: {
      bindings: [{ name: 'GUARD', class_name: 'AbuseGuard', script_name: options.name }],
    },
    ...(admin.auth === 'access' && admin.access
      ? {
          vars: {
            ACCESS_TEAM_DOMAIN: admin.access.team,
            ACCESS_AUD: admin.access.aud,
            ADMIN_EMAILS: admin.access.emails,
          },
        }
      : {}),
    observability: { enabled: false },
    ...(admin.domains.length ? { routes: routes(admin.domains) } : {}),
  };
  return `${JSON.stringify(config, null, 2)}\n`;
}

/** Both Wrangler files for these answers: adminText is null without the dashboard. */
export function renderInstance(publicText, options, dir) {
  const prefix = instancePrefix(dir);
  const result = renderPublic(publicText, options, prefix);
  const compatibilityDate = parse(result).compatibility_date;
  return {
    publicText: result,
    adminText: options.admin ? renderAdmin(options, prefix, compatibilityDate) : null,
  };
}

/** The answers that made these files, for running setup again. */
export function readOptions(publicText, adminText) {
  const site = parse(publicText);
  const admin = adminText ? parse(adminText) : null;
  const apiHosts = site.vars?.API_HOSTS ?? [];
  const hosts = (site.routes ?? []).map((route) => route.pattern ?? route);
  const named = site.vars?.SITE ? new URL(site.vars.SITE).hostname : undefined;
  const domains = hosts
    .filter((host) => !apiHosts.includes(host))
    .sort((a, b) => (a === named ? -1 : b === named ? 1 : 0));
  const namespace = (name) => site.ratelimits?.find((r) => r.name === name)?.namespace_id;
  const database = site.d1_databases?.find((d) => d.binding === 'ACTIVITY');
  const access = admin?.vars?.ACCESS_AUD
    ? {
        team: admin.vars.ACCESS_TEAM_DOMAIN,
        aud: admin.vars.ACCESS_AUD,
        emails: admin.vars.ADMIN_EMAILS,
      }
    : undefined;
  return {
    name: site.name,
    accountId: site.account_id,
    domains,
    apiHosts,
    namespaces: [namespace('NETWORK_RATE'), namespace('SITE_RATE')],
    admin:
      admin && database
        ? {
            domains: (admin.routes ?? []).map((route) => route.pattern ?? route),
            auth: access ? 'access' : 'password',
            ...(access ? { access } : {}),
            fileNames: site.vars?.RECORD_FILE_NAMES !== false,
            database: { name: database.database_name, id: database.database_id },
          }
        : null,
  };
}

/**
 * The sign-in a dashboard already has, for running setup again: Access settings kept as
 * values in its file, Access kept as secrets on its Worker (names from `wrangler secret
 * list`), or the password.
 */
export function signInDefault(admin, secretNames) {
  if (admin?.access) return { auth: 'access', accessSecrets: false };
  if (secretNames.includes('ACCESS_AUD')) return { auth: 'access', accessSecrets: true };
  return { auth: 'password', accessSecrets: false };
}
